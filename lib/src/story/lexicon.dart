  late final Map<String, List<VerbEntry>> verbForms = _buildVerbForms();
  late final Set<String> verbLemmas = {
    ...irregularVerbs.keys.where((k) => !k.endsWith('_')),
    ...regularVerbs.where((k) => !k.endsWith('_')),
  };

  Map<String, List<VerbEntry>> _buildVerbForms() {
    final out = <String, List<VerbEntry>>{};
    void add(String form, String lemma, VerbForm kind) {
      if (form.isEmpty) return;
      final list = out.putIfAbsent(form, () => []);
      if (!list.any((e) => e.lemma == lemma && e.form == kind)) {
        list.add(VerbEntry(lemma, kind));
      }
    }

    for (final lemma in verbLemmas) {
      add(lemma, lemma, VerbForm.base);
      add(_thirdPerson(lemma), lemma, VerbForm.thirdPerson);
      add(_gerund(lemma), lemma, VerbForm.gerund);
      final irr = irregularVerbs[lemma];
      if (irr != null) {
        add(irr[0], lemma, VerbForm.past);
        add(irr[1], lemma, VerbForm.participle);
        // Verbs with two accepted forms: "burned", "learned", "hanged".
        if (lemma == 'burn') {
          add('burned', lemma, VerbForm.past);
          add('burned', lemma, VerbForm.participle);
        }
      } else {
        final ed = _past(lemma);
        add(ed, lemma, VerbForm.past);
        add(ed, lemma, VerbForm.participle);
      }
    }
    return out;
  }

  static bool _vowel(String c) => 'aeiou'.contains(c);

  static String _thirdPerson(String v) {
    if (RegExp(r'(s|sh|ch|x|z|o)$').hasMatch(v)) return '${v}es';
    if (v.length > 1 && v.endsWith('y') && !_vowel(v[v.length - 2])) {
      return '${v.substring(0, v.length - 1)}ies';
    }
    return '${v}s';
  }

  static String _past(String v) {
    if (v.endsWith('e')) return '${v}d';
    if (v.length > 1 && v.endsWith('y') && !_vowel(v[v.length - 2])) {
      return '${v.substring(0, v.length - 1)}ied';
    }
    if (doubling.contains(v)) return '$v${v[v.length - 1]}ed';
    return '${v}ed';
  }

  static String _gerund(String v) {
    if (v.endsWith('ie')) return '${v.substring(0, v.length - 2)}ying';
    if (v.endsWith('e') && !RegExp(r'(ee|ye|oe)$').hasMatch(v)) {
      return '${v.substring(0, v.length - 1)}ing';
    }
    if (doubling.contains(v)) return '$v${v[v.length - 1]}ing';
    return '${v}ing';
  }

  /// The verb readings of [word] (lower case), or empty.
  List<VerbEntry> verbReadings(String word) => verbForms[word] ?? const [];

  /// UPOS candidates of a lower-case word from the closed classes alone.
  static Set<Upos> closedClass(String w) => {
    if (determiners.contains(w)) Upos.det,
    if (pronouns.contains(w)) Upos.pron,
    if (prepositions.contains(w)) Upos.adp,
    if (coordinators.contains(w)) Upos.cconj,
    if (subordinators.contains(w)) Upos.sconj,
    if (interjections.contains(w)) Upos.intj,
    if (beForms.contains(w) || haveForms.contains(w) || doForms.contains(w))
      Upos.aux,
    if (modalsPossible.contains(w) || modalsCertain.contains(w)) Upos.aux,
    if (numberWords.contains(w)) Upos.num,
    if (adverbs.contains(w)) Upos.adv,
  };
